#[cfg(test)]
mod tests {
    use glam::Vec3;

    use super::GroupDataComponentReplicatedState;
    use crate::hub::FragmentTypeInfo;
    use crate::serialize::{CARRIER_ENDIAN, ReadBuffer};

    /// A raid update in the shape live sends it: group 0 with the first and
    /// last raid member positions, then the join queue throttle flag, the
    /// last field of the group. The values are made up.
    const RAID_POSITIONS: &[u8] = &[
        0x01, // group 0 dirty
        0x80, // no field of 0..=6, more masks follow
        0x80, // 7..=13
        0x80, // 14..=20
        0x80, // 21..=27
        0x91, // fields 28 and 32 (raid member positions 0 and 4), more masks follow
        0x3c, 0x00, 0x40, 0x00, 0x42, 0x00, // raid member position 0: (1, 2, 3), three halves
        0xc2, 0x00, 0x00, 0x00, 0x3c, 0x00, // raid member position 4: (-3, 0, 1)
        0x80, // 35..=41, more masks follow
        0x40, // field 48
        0x01, // join queue throttle active
    ];

    #[test]
    fn raid_member_positions_decode_as_three_halves() {
        let mut rb = ReadBuffer::new(CARRIER_ENDIAN, RAID_POSITIONS);
        let fragment = FragmentTypeInfo::TypeIndex(3451)
            .decode_contents(&mut rb)
            .expect("group data contents decode");
        assert_eq!(rb.position(), RAID_POSITIONS.len());
        let state = fragment
            .downcast_ref::<GroupDataComponentReplicatedState>()
            .expect("type index 3451 is GroupDataComponentReplicatedState");
        assert_eq!(
            state.raid_member_position.value(),
            Some(&Vec3::new(1.0, 2.0, 3.0))
        );
        assert_eq!(
            state.raid_member_position_77.value(),
            Some(&Vec3::new(-3.0, 0.0, 1.0))
        );
        assert_eq!(state.raid_member_position_75.value(), None);
        assert_eq!(state.join_queue_throttle_active.value(), Some(&true));
    }
}
